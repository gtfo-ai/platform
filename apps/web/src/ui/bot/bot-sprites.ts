/**
 * The agent office's bot: the sign-in mascot (`peek-bot-sprite.ts`) drawn whole — sitting on an
 * unseen chair, facing the viewer — in eight poses, one per agent state. Pure data, in the same
 * format and the same six inks as the peek bot, so one renderer draws both.
 *
 * ## Where the pixels came from
 *
 * research 18's recipe, extended (`docs/research/18-sign-in-mascot/office-poses.md`): the Z-Image
 * Turbo master shrunk onto a larger green canvas, one Qwen-Image-Edit 2511 edit that completed the
 * body sitting, then one edit per pose of that sitting frame ("Keep the exact same robot …
 * Everything else stays identical"), so all eight are one character at one scale. Each was reduced
 * on one shared grid — bottom row = the lowest boot pixel, centre = the boots' centre column, 18
 * source px per sprite pixel at 768² — by majority vote snapped to the six inks in CIELAB (night
 * weighted ×1.5 so outlines survive). By hand afterwards: lone specks removed; the antenna redrawn
 * as one 2 × 2 beacon with a stalk; every eye restamped from one set of shapes (open 3 × 4, looking
 * up/down, closed line, X, smile); and rows 29–35 — the lower legs and boots — are one shared
 * drawing in every pose, so nothing below the knees moves when frames swap.
 *
 * Every layer is a grid, one character per sprite pixel, written without trailing transparent
 * cells. All poses are {@link BOT_COLS} × {@link BOT_ROWS} with the same baseline (the bottom row is
 * the floor under the boots) and the same centre column, so a pose swap never jumps. Drawn at 2–3
 * CSS px per sprite pixel for the office desk scene (`bot.tsx`, `seat.tsx`).
 */
